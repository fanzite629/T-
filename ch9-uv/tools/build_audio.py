"""Synthesize the narration line by line and derive the animation timeline from it.

Usage: python3 tools/build_audio.py --model <dir of matcha-icefall-zh-baker> --vocoder <vocos-22khz-univ.onnx>

Outputs
  src/timeline.js        window.TL = {duration, scenes:[{id,sec,t0,t1}], lines:[{scene,i,t0,t1,t}]}
  exports/narration.wav  the full narration track, aligned with the timeline
Per-line audio is cached under .tts-cache/ keyed by the spoken text.
"""
import argparse, hashlib, json, os, re
import numpy as np
import soundfile as sf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCENE_LEAD = 1.0      # silence at the start of each scene (visual transition)
LINE_GAP = 0.32       # silence between lines
SPEED = 1.1


def speakable(line):
    if 's' in line:
        t = line['s']
    else:
        t = re.sub(r'[_^]\{([^}]*)\}', r'\1', line['t']).replace('–', '到').replace('nm', '纳米')
    # the voice model has no pause token for these marks; map them to a comma pause
    for ch in '；—':
        t = t.replace(ch, '，')
    t = t.replace('“', '').replace('”', '').replace('，，', '，')
    # the Mandarin-only voice drops Latin letters: spell them the way a teacher would say them
    t = re.sub(r'[A-Za-z]+', lambda m: WORDS.get(m.group(0)) or ''.join(LETTERS.get(c, c) for c in m.group(0)), t)
    return t.replace(' ', '')


WORDS = {'max': '最大值', 'min': '最小值'}
LETTERS = {'A': '诶', 'B': '必', 'C': '西', 'D': '迪', 'E': '伊', 'F': '艾弗', 'K': '开', 'P': '皮', 'R': '阿尔',
           'b': '必', 'c': '西', 'd': '迪', 'f': '艾弗', 'n': '恩'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', required=True)
    ap.add_argument('--vocoder', required=True)
    args = ap.parse_args()
    d = args.model.rstrip('/') + '/'

    import sherpa_onnx
    cfg = sherpa_onnx.OfflineTtsConfig(
        model=sherpa_onnx.OfflineTtsModelConfig(
            matcha=sherpa_onnx.OfflineTtsMatchaModelConfig(
                acoustic_model=d + 'model-steps-3.onnx', vocoder=args.vocoder,
                lexicon=d + 'lexicon.txt', tokens=d + 'tokens.txt', dict_dir=d + 'dict'),
            num_threads=4),
        rule_fsts=f'{d}phone.fst,{d}date.fst,{d}number.fst')
    tts = sherpa_onnx.OfflineTts(cfg)

    script = json.load(open(os.path.join(ROOT, 'src/script.json'), encoding='utf-8'))
    cache = os.path.join(ROOT, '.tts-cache')
    os.makedirs(cache, exist_ok=True)

    sr = None
    chunks, lines, scenes = [], [], []
    t = 0.0

    def silence(sec):
        nonlocal t
        n = int(round(sec * sr))
        chunks.append(np.zeros(n, dtype=np.float32))
        t += n / sr

    for sc in script['scenes']:
        sr = sr or tts.sample_rate
        s0 = t
        silence(SCENE_LEAD)
        for i, ln in enumerate(sc['lines']):
            say = speakable(ln)
            key = hashlib.sha1(f'baker|{SPEED}|{say}'.encode()).hexdigest()[:16]
            fp = os.path.join(cache, key + '.wav')
            if os.path.exists(fp):
                audio, _ = sf.read(fp, dtype='float32')
            else:
                a = tts.generate(say, sid=0, speed=SPEED)
                audio = np.asarray(a.samples, dtype=np.float32)
                # trim leading/trailing near-silence so gaps are controlled here
                # gentle threshold + generous pre-roll so quiet initial consonants survive
                nz = np.where(np.abs(audio) > 0.003)[0]
                if len(nz):
                    pre = int(0.12 * a.sample_rate)
                    audio = audio[max(0, nz[0] - pre): nz[-1] + int(0.08 * a.sample_rate)]
                sf.write(fp, audio, a.sample_rate)
            t0 = t
            chunks.append(audio)
            t += len(audio) / sr
            lines.append({'scene': sc['id'], 'i': i, 't0': round(t0, 3), 't1': round(t, 3), 't': ln['t']})
            silence(LINE_GAP + ln.get('p', 0))
        scenes.append({'id': sc['id'], 'sec': sc['sec'], 't0': round(s0, 3), 't1': round(t, 3)})

    full = np.concatenate(chunks)
    peak = float(np.max(np.abs(full))) or 1.0
    full = full / peak * 0.89
    os.makedirs(os.path.join(ROOT, 'exports'), exist_ok=True)
    sf.write(os.path.join(ROOT, 'exports/narration.wav'), full, sr)
    tl = {'title': script['title'], 'duration': round(t, 3), 'scenes': scenes, 'lines': lines}
    with open(os.path.join(ROOT, 'src/timeline.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build_audio.py — do not edit by hand.\nwindow.TL = ')
        json.dump(tl, f, ensure_ascii=False, indent=1)
        f.write(';\n')
    print(f'duration {t:.1f}s, {len(lines)} lines')
    for s in scenes:
        print(f"  {s['id']:8s} {s['t0']:7.1f} – {s['t1']:7.1f}  ({s['t1'] - s['t0']:.1f}s)")


if __name__ == '__main__':
    main()
